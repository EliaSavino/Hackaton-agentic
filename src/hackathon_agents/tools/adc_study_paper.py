def _esc(x: Any) -> str:
    return _latex_escape(x)


def _fmt(x: Any, nd: int = 2) -> str:
    try:
        return f"{float(x):.{nd}f}"
    except (TypeError, ValueError):
        return "--"


def _trunc(s: str, n: int = 48) -> str:
    return s if len(s) <= n else s[: n - 3] + "..."


def build_study_paper(
    grid_path: str | Path,
    benchmark_path: str | Path | None,
    boltz_path: str | Path | None,
    out_dir: str | Path,
):
    """Write main + supplementary LaTeX (and figures) for the study."""
    try:
        out_dir = Path(out_dir)
        (out_dir).mkdir(parents=True, exist_ok=True)
        grid = json.loads(Path(grid_path).read_text(encoding="utf-8"))
        benchmark = json.loads(Path(benchmark_path).read_text(encoding="utf-8")) if benchmark_path and Path(benchmark_path).exists() else None
        boltz = json.loads(Path(boltz_path).read_text(encoding="utf-8")) if boltz_path and Path(boltz_path).exists() else None

        stats = grid_stats(grid)
        figures = render_figures(grid, stats, benchmark, boltz, out_dir / "figures")

        main = _render_main(grid, stats, benchmark, boltz, figures)
        supp = _render_supp(grid, stats, benchmark, boltz, figures)

        main_v = validate_latex_output(main)
        supp_v = validate_latex_output(supp)
        if not main_v.ok:
            return error_result("main LaTeX invalid: " + "; ".join(main_v.errors), {"errors": main_v.errors})
        main_path = out_dir / "adc_linker_study.tex"
        supp_path = out_dir / "adc_linker_study_supp.tex"
        main_path.write_text(main_v.normalized, encoding="utf-8")
        supp_path.write_text(supp_v.normalized if supp_v.ok else supp, encoding="utf-8")
        return ok_result(
            {"main": str(main_path), "supp": str(supp_path), "figures": {k: str(v) for k, v in figures.items()},
             "n_contexts": len(stats["contexts"]), "n_designed": len(stats["pooled"])},
            [str(main_path), str(supp_path)] + [str(v) for v in figures.values()],
        )
    except Exception as exc:  # pragma: no cover
        return error_result(str(exc), {"out_dir": str(out_dir)})


